def apply_fixes(conn, dry_run=False):
    cur = conn.cursor()
    log = logger.info

    if dry_run:
        # 预览模式: 统计
        log(f"[预览] 将删除 {len(DELETE_WRONG)} 条错误映射")
        log(f"[预览] 将新增 {len(ADD_CORRECT)} 条核心映射")
        for pid, sym, w, *reason in ADD_CORRECT[:10]:
            note = reason[0][:60] if reason else ""
            log(f"  + {pid:20s} → {sym}  w={w}  {note}")
        log(f"  ... 共 {len(ADD_CORRECT)} 条")
        return

    # 删除
    for pid, sym in DELETE_WRONG:
        cur.execute("DELETE FROM ref.product_stock_mapping WHERE product_id=%s AND symbol=%s", (pid, sym))

    # 新增/覆盖
    for pid, sym, weight, *reason in ADD_CORRECT:
        cur.execute(
            """INSERT INTO ref.product_stock_mapping (product_id, symbol, weight, effective_date, expired_date, version)
               VALUES (%s,%s,%s,'2000-01-01','2099-12-31','manual_fix_v2')
               ON CONFLICT (product_id, symbol, effective_date)
               DO UPDATE SET weight=EXCLUDED.weight, version=EXCLUDED.version""",
            (pid, sym, weight))

    conn.commit()

    cur.execute("SELECT COUNT(*) FROM ref.product_stock_mapping WHERE version='manual_fix_v2'")
    n = cur.fetchone()[0]
    log(f"修正完成: {len(DELETE_WRONG)}删除 + {len(ADD_CORRECT)}新增/覆盖 = {n}条标记为manual_fix_v2")

