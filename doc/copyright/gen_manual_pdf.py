def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class NumberedCanvas(_canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        n = len(self._saved)
        for st in self._saved:
            self.__dict__.update(st)
            if self._pageNumber > 1:  # 封面不画页眉
                self._draw_header(n)
            super().showPage()
        super().save()

    def _draw_header(self, total):
        self.setFont(FONT, 8.5)
        self.drawString(25 * mm, A4[1] - 14 * mm, f"{SOFT_NAME} {VERSION} 用户操作说明书")
        self.drawRightString(A4[0] - 25 * mm, A4[1] - 14 * mm,
                             f"{HOLDER}  第 {self._pageNumber} 页 共 {total} 页")
        self.setLineWidth(0.4)
        self.line(25 * mm, A4[1] - 16 * mm, A4[0] - 25 * mm, A4[1] - 16 * mm)


