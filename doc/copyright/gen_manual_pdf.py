class Diag(Flowable):
    """流程框图: 盒子 + 箭头, 坐标原点左下, 单位磅"""

    def __init__(self, width, height, boxes, arrows):
        Flowable.__init__(self)
        self.width = width
        self.height = height
        self.boxes = boxes    # (x, y, w, h, 文本, 可选双线)
        self.arrows = arrows  # (x1, y1, x2, y2)

    def draw(self):
        c = self.canv
        c.setFont(FONT, 9)
        for b in self.boxes:
            x, y, w, h, text = b[:5]
            c.setFillColor(colors.white)
            c.rect(x, y, w, h, fill=1, stroke=1)
            lines = text.split("\n")
            ty = y + h / 2 + (len(lines) - 1) * 5.5
            for ln in lines:
                c.drawCentredString(x + w / 2, ty, ln)
                ty -= 11
        for x1, y1, x2, y2 in self.arrows:
            c.setFillColor(colors.black)
            c.setStrokeColor(colors.black)
            c.line(x1, y1, x2, y2)
            # 箭头三角形
            import math
            ang = math.atan2(y2 - y1, x2 - x1)
            p = c.beginPath()
            p.moveTo(x2, y2)
            p.lineTo(x2 - 7 * math.cos(ang - 0.45), y2 - 7 * math.sin(ang - 0.45))
            p.lineTo(x2 - 7 * math.cos(ang + 0.45), y2 - 7 * math.sin(ang + 0.45))
            p.close()
            c.drawPath(p, fill=1, stroke=0)


